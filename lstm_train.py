import pandas as pd
import numpy as np

from sklearn.preprocessing import LabelEncoder, MinMaxScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error

from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, Dense

df = pd.read_csv('merged.csv')


# Clean text (VERY IMPORTANT)
df['commodity'] = df['commodity'].astype(str).str.strip()
df['mandi_location'] = df['mandi_location'].astype(str).str.strip()

print("Commodities:", df['commodity'].nunique())
print("Mandis:", df['mandi_location'].nunique())

df['date'] = pd.to_datetime(df['date'])

# Sort properly
df = df.sort_values(by=['commodity', 'mandi_location', 'date'])

# Fill ONLY numeric columns
num_cols = ['min_price', 'max_price', 'modal_price']
df[num_cols] = df[num_cols].fillna(method='ffill')

# Remove duplicates
df = df.drop_duplicates(subset=['commodity', 'mandi_location', 'date'])

le_commodity = LabelEncoder()
df['commodity_encoded'] = le_commodity.fit_transform(df['commodity'])

le_mandi = LabelEncoder()
df['mandi_encoded'] = le_mandi.fit_transform(df['mandi_location'])

features = [
    'commodity_encoded',
    'mandi_encoded',
    'min_price',
    'max_price'
]

target = 'modal_price'

scaler = MinMaxScaler()
df[features + [target]] = scaler.fit_transform(df[features + [target]])

SEQ_LEN = 3

def create_sequences(data, seq_length):
    X, y = [], []
    for i in range(len(data) - seq_length):
        X.append(data[i:i+seq_length])
        y.append(data[i+seq_length, -1])
    return np.array(X), np.array(y)

X_list, y_list = [], []

for commodity, df_com in df.groupby('commodity_encoded'):

    if len(df_com) < SEQ_LEN:
        continue

    data_values = df_com[features + [target]].values

    X_temp, y_temp = create_sequences(data_values, SEQ_LEN)

    if len(X_temp) > 0:
        X_list.append(X_temp)
        y_list.append(y_temp)

X = np.vstack(X_list)
y = np.hstack(y_list)

print("Training samples:", len(X))

split = int(0.8 * len(X))

X_train, X_test = X[:split], X[split:]
y_train, y_test = y[:split], y[split:]

model = Sequential()
model.add(LSTM(64, return_sequences=True, input_shape=(SEQ_LEN, len(features)+1)))
model.add(LSTM(32))
model.add(Dense(1))

model.compile(optimizer='adam', loss='mse')

model.fit(X_train, y_train, epochs=10, batch_size=32, verbose=1)
model.save("lstm_model.h5")
print("✅ Model saved successfully")

predictions = model.predict(X_test, verbose=0)

def inverse_transform(y_scaled):
    dummy = np.zeros((len(y_scaled), len(features) + 1))
    dummy[:, -1] = y_scaled.flatten()
    return scaler.inverse_transform(dummy)[:, -1]
import joblib
joblib.dump(scaler, "scaler.pkl")
print("✅ Scaler saved")

y_test_actual = inverse_transform(y_test)
predictions_actual = inverse_transform(predictions)

mae = mean_absolute_error(y_test_actual, predictions_actual)
rmse = np.sqrt(mean_squared_error(y_test_actual, predictions_actual))

print("MAE:", mae)
print("RMSE:", rmse)

grouped = df.sort_values('date').groupby(['commodity', 'mandi_location']).last().reset_index()

print("Total rows (should be large):", len(grouped))

results = []

for _, row in grouped.iterrows():

    commodity = row['commodity']
    mandi = row['mandi_location']

    min_price = row['min_price']
    max_price = row['max_price']
    modal_price = row['modal_price']

    # Get full history
    df_com = df[(df['commodity'] == commodity) & (df['mandi_location'] == mandi)].sort_values('date')

    if len(df_com) >= 3:
        last_seq = df_com[features + [target]].values[-3:]

        pred = model.predict(last_seq.reshape(1, 3, last_seq.shape[1]), verbose=0)
        forecast = inverse_transform(pred)[0]
    else:
        forecast = modal_price  # fallback

    results.append([
        commodity,
        mandi,
        min_price,
        max_price,
        modal_price,
        forecast,
        mae,
        rmse
    ])

final_df = pd.DataFrame(results, columns=[
    'Commodity',
    'Mandi',
    'Min Price',
    'Max Price',
    'Modal Price',
    'Forecast Price',
    'MAE',
    'RMSE'
])

final_df = final_df.round(2)

print("Final commodities:", final_df['Commodity'].nunique())
print("Final mandis:", final_df['Mandi'].nunique())

